"""Write the project's docs/code-map.md: one line per module, so a session finds code without searching.

    py -3 <harness>/tools/code_map.py [--check]        run from inside the project

Each line is the module's own first comment line, or its public names (Python, TypeScript) or the components
it renders (Svelte). Settings, all optional, in projects.toml under [<project>.code_map]: roots, skip.
"""

import ast
import re
import sys
from pathlib import Path
from typing import Any

from project import find_project, strings

ROOTS = (".",)
SKIP = (".venv", "venv", "node_modules", ".git", "docs", "static", "dist", "build", "__pycache__", "tests")
SUFFIXES = ("*.py", "*.ts", "*.svelte")
NAMES_SHOWN = 6

BLOCK_COMMENT = re.compile(r"^\s*/\*+(.*?)\*/", re.DOTALL)
HTML_COMMENT = re.compile(r"<!--(.*?)-->", re.DOTALL)
EXPORTED = re.compile(r"^export\s+(?:async\s+)?(?:function|const|class|type|interface)\s+(\w+)", re.MULTILINE)
IMPORTED_COMPONENT = re.compile(r"import\s+(\w+)\s+from\s+'[^']*\.svelte'")


def first_line(text: str) -> str:
    for line in text.splitlines():
        line = line.strip(" */#\t")
        if line:
            return line
    return ""


def names_text(names: list[str], prefix: str = "") -> str:
    if not names:
        return ""
    shown = ", ".join(names[:NAMES_SHOWN]) + (" …" if len(names) > NAMES_SHOWN else "")
    return f"{prefix} {shown}".strip()


def python_summary(source: str) -> str:
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return ""
    doc = ast.get_docstring(tree)
    if doc:
        return first_line(doc)
    kinds = ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef
    return names_text([n.name for n in tree.body if isinstance(n, kinds) and not n.name.startswith("_")])


def typescript_summary(source: str) -> str:
    block = BLOCK_COMMENT.match(source)
    if block:
        return first_line(block.group(1))
    leading = [line for line in source.splitlines()[:3] if line.startswith("//")]
    if leading:
        return first_line(leading[0])
    return names_text(EXPORTED.findall(source))


def svelte_summary(source: str) -> str:
    comment = HTML_COMMENT.search(source)
    if comment:
        return first_line(comment.group(1))
    return names_text(IMPORTED_COMPONENT.findall(source), prefix="uses")


def summary(path: Path) -> str:
    source = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix == ".py":
        return python_summary(source)
    if path.suffix == ".svelte":
        return svelte_summary(source)
    return typescript_summary(source)


def modules(repo: Path, settings: dict[str, Any]) -> list[Path]:
    skip = set(strings(settings, "skip", SKIP))
    found = {
        path
        for root in strings(settings, "roots", ROOTS)
        for suffix in SUFFIXES
        for path in (repo / root).rglob(suffix)
        if not skip.intersection(path.relative_to(repo).parts[:-1])
        and path.name not in skip
        and path.name != "__init__.py"
    }
    return sorted(found, key=lambda path: path.relative_to(repo).as_posix())


def build_map(repo: Path, settings: dict[str, Any]) -> str:
    lines = [
        "# Code map",
        "",
        "Generated by the harness `tools/code_map.py`; do not edit. One line per module: its own first",
        "comment line, or its public names (`uses` = components it renders). Read this before searching.",
    ]
    folder = None
    for path in modules(repo, settings):
        relative = path.relative_to(repo)
        if relative.parent != folder:
            folder = relative.parent
            lines += ["", f"## {folder.as_posix()}/", ""]
        note = summary(path)
        lines.append(f"- `{relative.name}`" + (f" — {note}" if note else ""))
    return "\n".join(lines) + "\n"


def main() -> int:
    project = find_project(Path.cwd())
    out = project.docs / "code-map.md"
    wanted = build_map(project.repo, project.tool("code_map"))
    if "--check" in sys.argv:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        print("code-map.md is up to date." if current == wanted else "code-map.md is out of date: run code_map.py.")
        return 0 if current == wanted else 1
    out.write_text(wanted, encoding="utf-8", newline="\n")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
